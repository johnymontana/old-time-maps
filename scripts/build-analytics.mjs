import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const notices = [];
for (const name of ['analytics', 'speed-insights']) {
  const directory = new URL(`../node_modules/@vercel/${name}/`, import.meta.url);
  const pkg = JSON.parse(await readFile(new URL('package.json', directory), 'utf8'));
  const license = await readFile(new URL('LICENSE', directory), 'utf8');
  notices.push(`@vercel/${name} ${pkg.version}\n\n${license.trim()}`);
}
const licenses = notices.join('\n\n') + '\n';
await build({
  absWorkingDir: root,
  entryPoints: ['web/analytics.js'],
  outfile: 'web/analytics.min.js',
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  define: { 'process.env.NODE_ENV': '"production"' },
  banner: { js: `/*! Generated by npm run build:analytics.\n${licenses}*/` },
});

await writeFile(new URL('../web/analytics.LICENSE.txt', import.meta.url), licenses);
console.log('Built web/analytics.min.js and license notices.');
